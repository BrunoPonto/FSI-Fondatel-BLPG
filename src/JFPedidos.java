    private void CBMesaItemStateChanged(java.awt.event.ItemEvent evt) {//GEN-FIRST:event_CBMesaItemStateChanged
        if (evt.getStateChange() == ItemEvent.SELECTED) {
            String mesa = CBMesa.getSelectedItem().toString();
            actualizarSillas(); // Recarga el combo de sillas según la mesa elegida
            
            if (mesa.equals("Todos")) {
                cnx.entablar(todos_pedidos, TPedido);
            } else {
                String sql = String.format(estado_por_mesa, mesa);
                cnx.entablar(sql, TPedido);
            }
        }
    }//GEN-LAST:event_CBMesaItemStateChanged

    private void CBSillaItemStateChanged(java.awt.event.ItemEvent evt) {//GEN-FIRST:event_CBSillaItemStateChanged
        if (evt.getStateChange() == ItemEvent.SELECTED && CBMesa.getSelectedItem() != null) {
            String mesa = CBMesa.getSelectedItem().toString();
            String silla = CBSilla.getSelectedItem().toString();
            
            if (!mesa.equals("Todos") && !silla.equals("Todos") && !silla.equals("Todas")) {
                String sql = String.format(consumo_mesa_silla, mesa, silla);
                cnx.entablar(sql, TPedido);
            } else if (!mesa.equals("Todos")) {
                String sql = String.format(estado_por_mesa, mesa);
                cnx.entablar(sql, TPedido);
            }
        }
    }//GEN-LAST:event_CBSillaItemStateChanged

