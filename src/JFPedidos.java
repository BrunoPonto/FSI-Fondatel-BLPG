    String consumo_mesa_silla = "SELECT DATE(fecha_hora) AS fecha, silla, nombrec AS cliente, COUNT(folio) AS total_articulos, SUM(precio) AS subtotal FROM pedidos WHERE mesas_numero = %s AND silla = %s AND estadoo IN ('ordenado', 'preparado', 'entregado') GROUP BY DATE(fecha_hora), silla, nombrec ORDER BY fecha DESC";
    String cancelados_devueltos = "SELECT folio, fecha_hora, mesas_numero, nombrec AS cliente, nombre AS platillo, estadoo, observaciones FROM pedidos WHERE estadoo IN ('cancelado', 'devuelto') AND fecha_hora BETWEEN '2026-11-16 00:00:00' AND '2026-12-31 23:59:59' ORDER BY fecha_hora DESC";
