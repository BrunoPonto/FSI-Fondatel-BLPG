    private void actualizarSillas() {
        if (CBMesa.getSelectedItem() == null) {
            return;
        }

        String mesaSeleccionada = CBMesa.getSelectedItem().toString();
        if (mesaSeleccionada.equals("Todos")) {
            CBSilla.removeAllItems();
            CBSilla.addItem("Todas");
        } else {
            String sqlSillas = String.format(sillas_por_mesa, mesaSeleccionada);
            cnx.seleccionar(sqlSillas, CBSilla);
        }
    }

