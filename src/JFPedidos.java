    String todos_pedidos = "SELECT folio, mesas_numero AS mesa, silla, nombrec AS cliente, nombre AS platillo, estadoo AS estado, precio FROM pedidos WHERE estadoo NOT IN ('pagado', 'cancelado') ORDER BY mesas_numero, silla";
