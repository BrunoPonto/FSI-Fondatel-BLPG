    private void BTotalMesaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BTotalMesaActionPerformed
        if (CBMesa.getSelectedItem() == null) return;
        
        String mesa = CBMesa.getSelectedItem().toString();
        if (mesa.equals("Todos")) {
            JOptionPane.showMessageDialog(this, "Selecciona una mesa específica en el combo para calcular su total.");
        } else {
            String sql = String.format(total_por_mesa, mesa);
            cnx.entablar(sql, TTicket);
        }
    }//GEN-LAST:event_BTotalMesaActionPerformed

    private void CBMesaItemStateChanged(java.awt.event.ItemEvent evt) {//GEN-FIRST:event_CBMesaItemStateChanged
        if (evt.getStateChange() == ItemEvent.SELECTED && CBMesa.getSelectedItem() != null) {
            String mesa = CBMesa.getSelectedItem().toString();
            if (mesa.equals("Todos")) {
                cnx.entablar(resumen_mesas, TTicket);
            } else {
                String sql = String.format(desglose_por_mesa, mesa);
                cnx.entablar(sql, TTicket);
            }
        }
    }//GEN-LAST:event_CBMesaItemStateChanged

    private void BDesgloseActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BDesgloseActionPerformed
        if (CBMesa.getSelectedItem() == null) return;
        
        String mesa = CBMesa.getSelectedItem().toString();
        if (mesa.equals("Todos")) {
            JOptionPane.showMessageDialog(this, "Selecciona una mesa específica en el combo para ver su desglose.");
        } else {
            String sql = String.format(desglose_por_mesa, mesa);
            cnx.entablar(sql, TTicket);
        }
    }//GEN-LAST:event_BDesgloseActionPerformed

